MOLIT_API_KEY = os.getenv("MOLIT_API_KEY")
BUILDING_PERMIT_API_KEY = os.getenv("BUILDING_PERMIT_API_KEY")
UNSOLD_HOUSING_API_KEY = os.getenv("UNSOLD_HOUSING_API_KEY")


def validate_api_keys() -> None:
    """
    필수 API 키가 설정됐는지 확인. 플레이스홀더 텍스트('여기에_' 포함)가
    남아있으면 실제 키로 교체되지 않은 것으로 간주하고 에러를 발생시킨다.
    수집기 실행 전에 호출해서 조용히 실패하는 상황을 방지한다.
    """
    keys = {
        "MOLIT_API_KEY": MOLIT_API_KEY,
        "BUILDING_PERMIT_API_KEY": BUILDING_PERMIT_API_KEY,
        "UNSOLD_HOUSING_API_KEY": UNSOLD_HOUSING_API_KEY,
    }
    missing = [
        name for name, value in keys.items()
        if not value or "여기에_" in value
    ]
    if missing:
        raise RuntimeError(
            f".env에 다음 API 키가 설정되지 않았습니다: {', '.join(missing)}"
        )


